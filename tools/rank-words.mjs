// Scores every word by how often it appears in spoken Turkish and writes data/ranks.js.
//
// Source: the FrequencyWords list built from OpenSubtitles (CC BY-SA 4.0),
// https://github.com/hermitdave/FrequencyWords — content/2018/tr/tr_50k.txt
//
// Usage: node tools/rank-words.mjs path/to/tr_50k.txt
//
// Nouns score the sum of their common case forms (ev, eve, evde, evim...).
// Verbs score the sum of their common conjugated forms (geliyorum, geldim...),
// because the dictionary form (gelmek) is rare in speech.
// Multi-word items score as their rarest word, scaled down per extra word.

import { readFileSync, writeFileSync } from 'node:fs';
import { WORDS } from '../data/words.js';
import { attach } from '../js/grammar.js';

const file = process.argv[2];
if (!file) {
  console.error('Usage: node tools/rank-words.mjs path/to/tr_50k.txt');
  process.exit(1);
}

const freq = new Map();
for (const line of readFileSync(file, 'utf8').replace(/^﻿/, '').split('\n')) {
  const [w, n] = line.trim().split(' ');
  // Case variants (Bir, BİR) are the same word, so add them up.
  const key = w && w.toLocaleLowerCase('tr');
  if (key && n) freq.set(key, (freq.get(key) || 0) + Number(n));
}
const count = (w) => freq.get(w.toLocaleLowerCase('tr')) || 0;

const NOUN_FORMS = ['', '(y)A', '(y)I', 'DA', 'DAn', '(I)m', '(I)n', '(s)I', '(n)In', 'lAr'];
// Forms that are usually other words are left out: the bare stem (var, de),
// the aorist (yer = place) and the polite imperative (için = for).
const VERB_FORMS = [
  'Iyor', 'Iyorum', 'Iyorsun', 'Iyoruz', 'DI', 'DIm', 'DIn', 'DIk', 'mIş', '(y)AcAk', '(y)AcAğIm',
  'RIm', 'mAk', 'mA', 'mIyor', 'mIyorum', 'mAdIm', 'mAdI', '(y)AbilIr', '(y)AlIm', 'mAm', 'mAyIn',
];

// Words that share their spelling with something more common.
const DAMPEN = {
  'food:et': 0.05, 'body:yüz': 0.3, 'numbers:yüz': 0.5, 'numbers:bin': 0.3, 'numbers:on': 0.3,
  'nature:kar': 0.5, 'work:iş': 0.4,
  // ada + -m = adam (man); hala is how subtitles spell hâlâ (still); gelin = come!; at = throw!;
  // ay = month; ayı = the month; koca = huge; deri + -n = derin (deep); dizi = the knee; un is noise.
  'nature:ada': 0.03, 'people:hala': 0.03, 'food:un': 0.02, 'people:gelin': 0.2, 'animals:at': 0.2,
  'nature:ay': 0.2, 'animals:ayı': 0.5, 'people:koca': 0.5, 'body:deri': 0.3, 'hobbies:dizi': 0.5,
};

const clean = (s) => s.replace(/[?!.,…]/g, '').replace(/\.\.\./g, '').trim();

function singleScore(word, token) {
  if (word.type === 'verb') {
    const w = { ...word, tr: token };
    return new Set(VERB_FORMS.map((s) => attach(w, s))).values().reduce((sum, f) => sum + count(f), 0);
  }
  if (word.type === 'noun') {
    const w = { ...word, tr: token, cmp: false };
    return new Set(NOUN_FORMS.map((s) => attach(w, s))).values().reduce((sum, f) => sum + count(f), 0);
  }
  return count(token);
}

function score(word) {
  if (word.tr === 'de / da') return count('de') + count('da');
  const tokens = clean(word.tr).split(/\s+/).filter((t) => t && t !== '/');
  if (tokens.length === 1) return singleScore(word, tokens[0]);
  // Multi-word: verbs are scored by their first word and their verb; others by their rarest word.
  if (word.type === 'verb') {
    const verb = tokens[tokens.length - 1];
    return Math.min(count(tokens[0]), singleScore(word, verb));
  }
  // Each word of a phrase is far more common than the whole phrase, so scale down per extra word.
  return Math.min(...tokens.map((t) => count(t))) / 4 ** (tokens.length - 1);
}

const ranks = {};
for (const w of WORDS) ranks[w.id] = Math.round(score(w) * (DAMPEN[w.id] || 1));

const body = Object.entries(ranks)
  .map(([id, n]) => `  ${JSON.stringify(id)}: ${n},`)
  .join('\n');
writeFileSync(
  new URL('../data/ranks.js', import.meta.url),
  `// Generated by tools/rank-words.mjs from the OpenSubtitles frequency list (CC BY-SA 4.0).\n` +
    `// Higher = more common in spoken Turkish.\nexport const RANKS = {\n${body}\n};\n`,
);

const top = Object.entries(ranks).sort((a, b) => b[1] - a[1]);
console.log('Top 40:', top.slice(0, 40).map(([id]) => id.split(':')[1]).join(', '));
console.log('Zero-scored:', top.filter(([, n]) => n === 0).map(([id]) => id).join(', ') || 'none');
